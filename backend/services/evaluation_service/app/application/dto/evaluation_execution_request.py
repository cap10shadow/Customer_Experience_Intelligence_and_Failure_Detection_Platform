import uuid
from dataclasses import dataclass
from typing import Optional

from backend.services.evaluation_service.app.application.completed_intelligence import CompletedIntelligence


@dataclass(frozen=True)
class EvaluationExecutionRequest:
    """
    Evaluation Execution Request DTO (Application-owned)

    Operational Purpose:
    The "Application request" the Infrastructure Event Consumer produces
    from a deserialized `BusinessImpactCompleted` transport payload, and
    the sole input `EvaluationLifecycleService.execute()` accepts. It is
    the Consumer's entire "translate transport payload into an Application
    request" responsibility, expressed as a type: once this object exists,
    nothing downstream needs to know anything about transport, wire
    formats, or messaging.

    Architectural Boundaries:
    - `event_id` is the inbound event's own identifier -- the value the
      idempotency check and the database UNIQUE constraint are keyed on.
      It is never generated by this service; it must already exist on the
      event as received.
    - `root_cause_id` / `assessment_id` are the upstream Root Cause and
      Business Impact Assessment identifiers the event carries -- plain
      `uuid.UUID`, never those services' own domain/ORM types (DATA-002).
      `assessment_id` becomes `EvaluationRecord.business_impact_id` once
      persisted; the naming here matches the event's own vocabulary
      (a Business Impact *Assessment* completed).
    - `completed_intelligence` is the existing, frozen Step 1
      `CompletedIntelligence` DTO, reused verbatim -- Step 3 does not
      change what the Domain engines consume, only how it now arrives.
    """

    event_id: uuid.UUID
    root_cause_id: Optional[uuid.UUID]
    assessment_id: Optional[uuid.UUID]
    completed_intelligence: CompletedIntelligence
